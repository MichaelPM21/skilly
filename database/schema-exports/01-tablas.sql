-- PostgreSQL. Scripts académicos para una base DESECHABLE; no ejecutar DROP sobre la base de trabajo.
CREATE TABLE access_tokens (
        token_hash TEXT, purpose TEXT NOT NULL, subject TEXT NOT NULL,
        expires_at BIGINT NOT NULL, used_at BIGINT
      );

CREATE TABLE attachments (
        id TEXT, booking_id TEXT NOT NULL,
        name TEXT NOT NULL, mime TEXT NOT NULL, data BYTEA NOT NULL,
        created_by TEXT NOT NULL, created_at BIGINT NOT NULL
      );

CREATE TABLE audit_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY, actor TEXT, action TEXT NOT NULL,
        target TEXT, detail TEXT, created_at BIGINT NOT NULL
      );

CREATE TABLE bookings (
  id TEXT,
  professional_id TEXT NOT NULL,
  professional_name TEXT,
  professional_email TEXT,
  org_name TEXT,
  org_email TEXT,
  date TEXT,
  time TEXT,
  service TEXT,
  notes TEXT,
  amount BIGINT,
  status TEXT NOT NULL DEFAULT 'reservado', -- reservado | pagado | entregado | completado | cancelado
  created_at BIGINT NOT NULL,
  delivered_at BIGINT, refund_amount BIGINT, refund_percent BIGINT, cancelled_at BIGINT, cancelled_by TEXT, cancel_reason TEXT, service_id TEXT, org_user_id TEXT, guest BIGINT NOT NULL DEFAULT 0, service_snapshot TEXT NOT NULL DEFAULT '{}', commission_percent DOUBLE PRECISION NOT NULL DEFAULT 15, commission_amount BIGINT NOT NULL DEFAULT 0, professional_net BIGINT NOT NULL DEFAULT 0, response_deadline BIGINT, payment_deadline BIGINT, paid_at BIGINT, confirmed_at BIGINT, terms_accepted_at BIGINT, terms_version TEXT, duration_minutes BIGINT NOT NULL DEFAULT 60, prep_minutes BIGINT NOT NULL DEFAULT 0, followup_minutes BIGINT NOT NULL DEFAULT 0, start_at BIGINT, end_at BIGINT, refund_policy_percent DOUBLE PRECISION NOT NULL DEFAULT 80, cancellation_status TEXT, policy_snapshot TEXT, delivery_evidence TEXT, retained_amount BIGINT NOT NULL DEFAULT 0, retention_destination TEXT
);

CREATE TABLE case_events(id TEXT, case_id TEXT NOT NULL, actor TEXT, kind TEXT NOT NULL, body TEXT NOT NULL, created_at BIGINT NOT NULL ,event_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE);

CREATE TABLE evaluations (
  id TEXT,
  professional_id TEXT NOT NULL,
  professional_name TEXT,
  booking_id TEXT,
  org_name TEXT,
  org_email TEXT,
  stars BIGINT NOT NULL,
  comment TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE guest_requests (
  id TEXT,
  professional_id TEXT NOT NULL,
  professional_name TEXT,
  contact_name TEXT NOT NULL,
  org_name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  date TEXT,
  time TEXT,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'nueva', -- nueva | contactada | convertida | descartada
  admin_notes TEXT DEFAULT '',
  booking_id TEXT,                       -- se llena si se convierte en reserva formal
  email_sent BIGINT NOT NULL DEFAULT 0,
  created_at BIGINT NOT NULL,
  handled_at BIGINT, assigned_to TEXT DEFAULT '', service_id TEXT
);

CREATE TABLE incidents (
        id TEXT, booking_id TEXT NOT NULL,
        author_id TEXT, body TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'abierta',
        resolution TEXT, created_at BIGINT NOT NULL, resolved_at BIGINT
      , category TEXT NOT NULL DEFAULT 'otro', requested_remedy TEXT NOT NULL DEFAULT 'revision', assigned_to TEXT, response_due BIGINT, resolution_due BIGINT, outcome TEXT, evidence TEXT, appeals BIGINT NOT NULL DEFAULT 0);

CREATE TABLE messages (
  id TEXT,
  booking_id TEXT NOT NULL,
  sender_role TEXT NOT NULL,   -- organizacion | profesional | admin
  sender_name TEXT,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE outbox (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY, recipient TEXT NOT NULL, subject TEXT NOT NULL,
        body TEXT NOT NULL, sent BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL
      , attempts BIGINT NOT NULL DEFAULT 0, next_attempt_at BIGINT NOT NULL DEFAULT 0, lease_until BIGINT NOT NULL DEFAULT 0, last_error TEXT, dedupe_key TEXT);

CREATE TABLE payments (
  id TEXT,
  booking_id TEXT NOT NULL,
  professional_id TEXT,
  professional_name TEXT,
  org_name TEXT,
  org_email TEXT,
  amount BIGINT,
  method TEXT,
  status TEXT NOT NULL DEFAULT 'pagado', -- iniciado | pagado (retenido) | liberado | rechazado
  invoice_number TEXT,
  created_at BIGINT NOT NULL,
  released_at BIGINT,
  provider TEXT DEFAULT 'simulado',      -- simulado | webpay | paypal
  provider_token TEXT,                   -- token_ws (Webpay) u order id (PayPal)
  buy_order TEXT,                        -- buyOrder enviado a Webpay
  authorization_code TEXT,               -- código de autorización DOUBLE PRECISION del emisor
  card_last4 TEXT,
  payment_type_code TEXT,
  currency TEXT DEFAULT 'CLP', refund_amount BIGINT, refund_id TEXT, refunded_at BIGINT, expected_currency TEXT, expected_amount DOUBLE PRECISION, operation_key TEXT
);

CREATE TABLE payouts(id TEXT,booking_id TEXT NOT NULL UNIQUE,amount BIGINT NOT NULL,status TEXT NOT NULL,reference TEXT UNIQUE,evidence_id TEXT,created_at BIGINT NOT NULL,confirmed_at BIGINT);

CREATE TABLE professionals (
  id TEXT,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  category TEXT,
  title TEXT,
  description TEXT,
  tags TEXT,              -- JSON array
  price TEXT,
  modality TEXT,
  status TEXT NOT NULL DEFAULT 'pendiente',   -- pendiente | validado | rechazado
  recommended BIGINT NOT NULL DEFAULT 0,      -- 0/1 — decidido por el admin, reemplaza ranking público
  admin_notes TEXT DEFAULT '',
  validation TEXT,        -- JSON: {linkedin, yearsExperience, certifications, cv, references, portfolio, motivation}
  availability TEXT,      -- JSON: {days:[...], hours:[...]}
  created_at BIGINT NOT NULL,
  reviewed_at BIGINT
, max_per_day BIGINT, max_per_week BIGINT, max_per_month BIGINT, duration_minutes BIGINT DEFAULT 60, prep_minutes BIGINT DEFAULT 0, followup_minutes BIGINT DEFAULT 0, assigned_to TEXT DEFAULT '', blocked_dates TEXT NOT NULL DEFAULT '[]', work_start TEXT NOT NULL DEFAULT '08:00', work_end TEXT NOT NULL DEFAULT '19:00', booking_suspended BIGINT NOT NULL DEFAULT 0, suspension_reason TEXT NOT NULL DEFAULT '');

CREATE TABLE refund_operations(id TEXT,booking_id TEXT NOT NULL,payment_id TEXT,amount BIGINT NOT NULL,percent DOUBLE PRECISION NOT NULL,reason TEXT NOT NULL,status TEXT NOT NULL,reference TEXT,evidence TEXT,created_at BIGINT NOT NULL, kind TEXT NOT NULL DEFAULT 'cancelacion');

CREATE TABLE IF NOT EXISTS schema_migrations (version TEXT, applied_at BIGINT NOT NULL);

CREATE TABLE service_appeals(id TEXT,service_id TEXT NOT NULL,revision TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'abierta',body TEXT NOT NULL,contact TEXT NOT NULL,due_at BIGINT NOT NULL,assigned_to TEXT,resolution TEXT,created_at BIGINT NOT NULL);

CREATE TABLE services (
        id TEXT, professional_id TEXT NOT NULL,
        published TEXT, draft TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pendiente',
        admin_notes TEXT NOT NULL DEFAULT '', commission_percent DOUBLE PRECISION,
        created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
      );

CREATE TABLE sessions (
        token_hash TEXT, user_id TEXT, guest_booking_id TEXT,
        audience TEXT NOT NULL, expires_at BIGINT NOT NULL
      );

CREATE TABLE settings (
  id BIGINT CHECK (id = 1),
  admin_weekly_review_capacity BIGINT NOT NULL DEFAULT 3,
  default_cancellation_refund_percent BIGINT NOT NULL DEFAULT 80
, commission_percent DOUBLE PRECISION NOT NULL DEFAULT 15, response_hours BIGINT NOT NULL DEFAULT 24, payment_hours BIGINT NOT NULL DEFAULT 24);

CREATE TABLE users (
        id TEXT, email TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
        password_hash TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN ('admin','profesional','organizacion')),
        professional_id TEXT, active BIGINT NOT NULL DEFAULT 1, verified BIGINT NOT NULL DEFAULT 0,
        profile TEXT NOT NULL DEFAULT '{}', created_at BIGINT NOT NULL
      );
